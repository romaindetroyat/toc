// Copies the self-hosted fonts and generates the icon data from the packages approved in plan
// 01-01 (@fontsource-variable/nunito, @fontsource-variable/caveat, lucide-static). Nothing is
// downloaded: the files come from apps/web/node_modules. Run it after changing the lists below:
//
//   node tools/copy-vendor-assets.mjs
//
// Outputs (committed):
//   apps/web/src/assets/fonts/{nunito,caveat}-{latin,latin-ext}.woff2 + OFL-{Nunito,Caveat}.txt
//   apps/web/src/ui/icons.ts (18 Lucide icons as data, ISC licence header)

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modules = path.join(root, "apps/web/node_modules");
const fontsOut = path.join(root, "apps/web/src/assets/fonts");
const iconsOut = path.join(root, "apps/web/src/ui/icons.ts");

/** Fontsource variable families: source package, file stem, output stem, licence file. */
const FAMILIES = [
  { pkg: "@fontsource-variable/nunito", stem: "nunito", licence: "OFL-Nunito.txt" },
  { pkg: "@fontsource-variable/caveat", stem: "caveat", licence: "OFL-Caveat.txt" },
];
const SUBSETS = ["latin", "latin-ext"];

/** Exactly the icons of UI-SPEC « Design System » (phase 1, then the six of 02-UI-SPEC). */
const ICON_NAMES = [
  "settings",
  "fast-forward",
  "undo-2",
  "x",
  "check",
  "hourglass",
  "play",
  "volume-2",
  "volume-x",
  "copy",
  "chevron-down",
  "rotate-ccw",
  "users",
  "share-2",
  "message-circle",
  "wifi-off",
  "bot",
  "crown",
];

mkdirSync(fontsOut, { recursive: true });
for (const { pkg, stem, licence } of FAMILIES) {
  for (const subset of SUBSETS) {
    // Fontsource names the upright variable file <stem>-<subset>-wght-normal.woff2.
    copyFileSync(
      path.join(modules, pkg, "files", `${stem}-${subset}-wght-normal.woff2`),
      path.join(fontsOut, `${stem}-${subset}.woff2`),
    );
  }
  copyFileSync(path.join(modules, pkg, "LICENSE"), path.join(fontsOut, licence));
}

const lucide = path.join(modules, "lucide-static");
const lucideVersion = JSON.parse(readFileSync(path.join(lucide, "package.json"), "utf8")).version;
const lucideLicence = readFileSync(path.join(lucide, "LICENSE"), "utf8").trim();
const nodes = JSON.parse(readFileSync(path.join(lucide, "icon-nodes.json"), "utf8"));

const quote = (text) => JSON.stringify(String(text));
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name));

let body = "";
for (const name of ICON_NAMES) {
  const elements = nodes[name];
  if (!Array.isArray(elements)) throw new Error(`lucide-static has no icon "${name}"`);
  body += `  ${key(name)}: [\n`;
  for (const [tag, attrs] of elements) {
    body += "    {\n";
    body += `      tag: ${quote(tag)},\n`;
    body += "      attrs: {\n";
    for (const [attr, value] of Object.entries(attrs)) {
      body += `        ${key(attr)}: ${quote(value)},\n`;
    }
    body += "      },\n";
    body += "    },\n";
  }
  body += "  ],\n";
}

const licenceComment = lucideLicence
  .split("\n")
  .map((line) => (line ? ` * ${line}` : " *"))
  .join("\n");

const source = `// Generated by tools/copy-vendor-assets.mjs from lucide-static ${lucideVersion}. Do not edit.
//
/**
 * Icons from Lucide (https://lucide.dev), ISC licence:
 *
${licenceComment}
 *
 * Each icon is the list of its SVG elements on a 24 x 24 grid (stroke currentColor, width 2,
 * round caps and joins): data only, rendered by Icon.svelte, never injected as markup.
 */
export const ICONS = {
${body}} as const;

export type IconName = keyof typeof ICONS;
`;

writeFileSync(iconsOut, source);
console.log(`fonts -> ${path.relative(root, fontsOut)}, icons -> ${path.relative(root, iconsOut)}`);
